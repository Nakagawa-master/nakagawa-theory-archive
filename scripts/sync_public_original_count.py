#!/usr/bin/env python3
"""Synchronize approved public original counts from the one canonical map.

The rendered Markdown contains literal numbers, regenerated by GitHub Actions
after a canonical map change; no human-facing sentence is otherwise rewritten.
New WordPress-only posts count only once registered in this official map.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "derivatives" / "official-derivatives-map.json"
PAGES = {
    ROOT / "README.md": "derivatives/",
    ROOT / "human-translation" / "who-is-nakagawa-master.md": "../derivatives/",
}
BEGIN = "<!-- BEGIN AUTO:OFFICIAL_ORIGINAL_COUNT -->"
END = "<!-- END AUTO:OFFICIAL_ORIGINAL_COUNT -->"

# Only the NUMBER within the approved reader sentence is writable.
# Never regenerate/reword an approved introduction.
INLINE_FIELDS = {
    ROOT / "README.md": (
        ("explore the ", " original theories and inspect independent developer evidence"),
        ("中川マスター（Nakagawa Master ／ pen-name of Keisuke Nakagawa）は、", "件の独立したオリジナル理論の原著者です。"),
    ),
    ROOT / "human-translation" / "who-is-nakagawa-master.md": (
        ("中川マスター（Nakagawa Master／公開名 Keisuke Nakagawa）は、", "本の独立した公開原典を構築し"),
    ),
    ROOT / "llms.txt": (
        ("— ", " equal Parents;"),
        ("- [", " original Parent URLs]"),
        ("- [English summaries for all ", "]("),
        ("- [Chinese summaries for all ", "]("),
    ),
}


def get_count_and_last() -> tuple[int, int]:
    entries = json.loads(MAP.read_text(encoding="utf-8"))["entries"]
    numbers = sorted(int(row["number"]) for row in entries)
    if not numbers or numbers != list(range(1, len(entries) + 1)):
        raise ValueError("Official original numbers are missing, duplicated, or noncontiguous")
    for entry in entries:
        if entry.get("status") != "active" or not entry.get("canonical_parent_url"):
            raise ValueError("Map includes inactive original or lacks a canonical Parent URL")
    parent_urls = [row["canonical_parent_url"] for row in entries]
    if len(parent_urls) != len(set(parent_urls)):
        raise ValueError("Official Parent map contains duplicate canonical URLs")
    return len(entries), numbers[-1]


def generated(count: int, last: int, derivative_link: str) -> str:
    return (
        f"{BEGIN}\n"
        f"**公開原典：{count}件。** [原典の正本](https://master.ricette.jp/) ／ "
        f"[公式派生物 OD001〜OD{last:03d}]({derivative_link})\n"
        f"{END}"
    )


def update_content(original: str, replacement: str) -> str:
    if original.count(BEGIN) != 1 or original.count(END) != 1:
        raise ValueError("Missing or duplicate original-count marker")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    new, n = pattern.subn(lambda _match: replacement, original)
    if n != 1:
        raise ValueError("Unexpected generated-block replacement count")
    return new


def update_inline_numbers(body: str, path: Path, count: int) -> str:
    # Only the numeric capture is editable. Each approved source sentence must
    # occur exactly once; a layout change becomes an explicit review failure.
    for prefix, suffix in INLINE_FIELDS[path]:
        pattern = re.compile(
            "(" + re.escape(prefix) + r")(\\d+)(" + re.escape(suffix) + ")"
        )
        matches = list(pattern.finditer(body))
        if len(matches) != 1:
            raise ValueError(
                f"{path.relative_to(ROOT)}: expected exactly one approved count sentence"
            )
        match = matches[0]
        body = body[: match.start(2)] + str(count) + body[match.end(2) :]
    return body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated counts are stale")
    args = parser.parse_args()
    count, last = get_count_and_last()
    pending = []
    for path in sorted(set(PAGES) | set(INLINE_FIELDS)):
        before = path.read_text(encoding="utf-8")
        after = before
        if path in PAGES:
            after = update_content(after, generated(count, last, PAGES[path]))
        if path in INLINE_FIELDS:
            after = update_inline_numbers(after, path, count)
        if before != after:
            pending.append(path)
            if not args.check:
                path.write_text(after, encoding="utf-8")
    if pending:
        print("Stale original counts:", ", ".join(str(p.relative_to(ROOT)) for p in pending))
    else:
        print(f"Official count current: {count} originals, OD001 through OD{last:03d}")
    return int(args.check and bool(pending))


if __name__ == "__main__":
    raise SystemExit(main())
